'use strict';
const assert = require('assert');
const fs = require('fs');
const path = require('path');
const { topicImages, routeImageKeys, topicImageFor } = require('./site-images');
const { doctors } = require('./quantum-health');
const { articles } = require('./published-blogs');
const root = path.join(__dirname, '..', 'public');
const local = (asset) => path.join(root, asset.replace(/^\//, ''));
Object.entries(topicImages).forEach(([key, asset]) => assert(fs.existsSync(local(asset)), `Missing canonical topic asset ${key}: ${asset}`));
Object.entries(routeImageKeys).forEach(([route]) => assert(topicImageFor(route), `No canonical topic image for ${route}`));
doctors.forEach((doctor) => assert(doctor.portrait && fs.existsSync(local(doctor.portrait)), `Missing portrait for ${doctor.name}: ${doctor.portrait || 'none'}`));
assert(fs.existsSync(local('/dr-sunitha-devaraj.png')), 'Missing portrait for Dr. Sunitha Devaraj');
articles.forEach((article) => assert(fs.existsSync(local(article.image)), `Missing blog image for ${article.title}: ${article.image}`));
console.log(`Image registry verified: ${Object.keys(topicImages).length} topic images, ${doctors.length} portraits, ${articles.length} blog images.`);
