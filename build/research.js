/* Research library: the complete PubMed Central literature set for the exact
   phrase "breast enlargement". The dataset is generated by build/fetch-pmc.js
   and served as a static JSON asset; this module renders the page shell. */

const fs = require('fs');
const path = require('path');
const { site, stdCta } = require('./content');

const DATA = path.join(__dirname, '..', 'public', 'assets', 'data', 'pmc-breast-enlargement.json');

function stats() {
  try {
    const data = JSON.parse(fs.readFileSync(DATA, 'utf8'));
    const years = data.articles.map((a) => a.year).filter(Boolean);
    return {
      total: data.total || data.articles.length,
      from: data.yearRange ? data.yearRange[0] : Math.min(...years),
      to: data.yearRange ? data.yearRange[1] : Math.max(...years),
      abstracts: data.withAbstract || data.articles.filter((a) => a.abstract).length,
      journals: data.journals || new Set(data.articles.map((a) => a.journal)).size,
      generated: data.generated || ''
    };
  } catch (err) {
    return { total: 0, from: null, to: null, abstracts: 0, journals: 0, generated: '' };
  }
}

